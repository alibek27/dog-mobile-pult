#!/bin/bash
# ЛЁГКАЯ КОПИЯ КАМЕРЫ ДЛЯ ТЕЛЕФОНА.
#
# ЗАЧЕМ. Телефон смотрит собаку через мобильный интернет. Два обычных потока
# (cam 2.0 Мбит/с + cam_low 1.4 Мбит/с) забивают отдачу 4G, и в очередь встаёт
# ВСЁ: джойстик, рация, кнопки. Замер 19.09: пинг до телефона при открытом
# видео 600-1066 мс, без видео 36 мс. Лёгкая копия 640x360 занимает ~270
# кбит/с — в пять раз меньше, и канал остаётся свободным для управления.
#
# ИСХОДНИКИ НЕ ТРОГАЕМ. Берём готовый поток из самого MediaMTX и кладём рядом
# новым путём. cam и cam_low остаются как были — cam_low смотрит площадка
# заказчика, и менять его содержимое нельзя.
#
# ВСЁ ЖЕЛЕЗОМ. На shym1 (Orin NX) есть работающий NVENC: nvv4l2decoder
# раскодирует, nvv4l2h264enc сожмёт, процессор при этом занят на 4%.
# ⚠️ Комментарий в shym1_camera.sh «аппаратно кодировать нечем» относится к
# ПЕРВОЙ собаке (Orin Nano, там NVENC вырезан на кремнии), не к этой.
set -eu

SRC=${TINY_SRC:-rtsp://127.0.0.1:8554/cam_low}
OUT=${TINY_OUT:-cam_tiny}
W=${TINY_W:-640}; H=${TINY_H:-360}
BR=${TINY_BITRATE:-500000}          # бит/с, CBR; реально выходит ~270 кбит/с
# Лёгкие копии живут в СВОЁМ раздатчике (mediamtx-tiny.yml): основной строит
# кабинет на ноутбуке, и лишние пути там превращались в лишние окна камер.
API=${TINY_API:-127.0.0.1:9994}
RTMP=${TINY_RTMP:-127.0.0.1:1936}
GOP=${TINY_GOP:-30}                 # опорный кадр раз в секунду: быстрый старт картинки

# Путь в MediaMTX может отсутствовать в конфиге — добавляем на ходу, без
# перезапуска раздатчика: перезапуск оборвал бы поток заказчику.
# Путь обычно уже описан в mediamtx-tiny.yml; попытка добавить его на ходу
# оставлена как страховка на случай чистого конфига и ничего не ломает.
curl -s -m 5 -X POST -H "Content-Type: application/json" -d '{}' \
     "http://$API/v3/config/paths/add/$OUT" >/dev/null 2>&1 || true

echo "лёгкая копия: $SRC -> ${W}x${H} ${BR} бит/с -> /$OUT (кодирует NVENC)"

# latency=100 у rtspsrc — буфер приёма. Меньше делать нельзя: локальный поток
# идёт через петлю, но рывки сети площадки на нём тоже отражаются.
# insert-sps-pps=1 — заголовки в каждом опорном кадре: без них плеер,
# подключившийся в середине, ждёт следующий GOP и показывает чёрное.
exec gst-launch-1.0 -e \
  rtspsrc location="$SRC" protocols=tcp latency=100 \
  ! rtph264depay ! h264parse ! nvv4l2decoder \
  ! nvvidconv ! "video/x-raw(memory:NVMM),width=$W,height=$H" \
  ! nvv4l2h264enc bitrate="$BR" iframeinterval="$GOP" insert-sps-pps=1 \
                  control-rate=1 preset-level=1 maxperf-enable=1 \
  ! h264parse config-interval=1 ! flvmux streamable=true \
  ! queue max-size-buffers=200 \
  ! rtmpsink location="rtmp://$RTMP/$OUT live=1"
