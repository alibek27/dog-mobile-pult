#!/bin/bash
# Пересобрать заплатки к службам собаки из файлов в папке «службы».
#
# ПОЧЕМУ ЗАПЛАТКИ, А НЕ ФАЙЛЫ ЦЕЛИКОМ. Службы управления (ctl) и защищённого
# входа (ptt) написаны до нас и принадлежат комплекту заказчика. Выкладывать
# их целиком мы не стали — в репозитории лежит только разница, то есть ровно
# то, что добавили мы.
#
# Рабочие файлы служб лежат в «службы/» и в git НЕ попадают (см. .gitignore):
#   службы/ctl.py            — наш изменённый файл
#   службы/ctl.py.исходник   — тот же файл до наших правок
#   службы/ptt.py            — наш изменённый файл
#   службы/ptt.py.исходник   — тот же файл до наших правок
#
# Порядок работы: правим службы/*.py -> заливаем на собаку -> запускаем этот
# скрипт -> коммитим. Тогда заплатка в репозитории всегда описывает то, что
# реально стоит на роботе.
#
# Имена переменных латиницей НАМЕРЕННО: bash не принимает кириллицу в именах.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRV="$HERE/службы"

make_patch() {
    orig="$SRV/$1.исходник"
    ours="$SRV/$1"
    out="$HERE/patches/$2"
    if [ ! -f "$orig" ] || [ ! -f "$ours" ]; then
        echo "  нет пары файлов для $1 — пропускаю" >&2
        return
    fi
    # diff возвращает 1, когда различия есть; для нас это норма, а не ошибка.
    diff -u "$orig" "$ours" > "$out" || true
    n=$(grep -c '^[+-]' "$out" || true)
    echo "  $2  ($n изменённых строк)"
}

echo "== заплатки пересобраны:"
make_patch ctl.py ctl-raciya-gromkost-zaderzhka.patch
make_patch ptt.py ptt-stranica-telefona-i-zaderzhka.patch

# Сторож: в заплатки не должны утекать пароли, ключи и адреса робота.
DANGER="12341234|sk-[A-Za-z0-9]{20}|100\.[0-9]+\.[0-9]+\.[0-9]+"
if grep -rniE "$DANGER" "$HERE/patches" >/dev/null 2>&1; then
    echo "⚠️  В заплатках нашлось похожее на пароль, ключ или адрес робота:" >&2
    grep -rniE "$DANGER" "$HERE/patches" | head -5 >&2
    echo "   Проверьте перед коммитом." >&2
    exit 1
fi
echo "проверка на пароли и адреса: чисто"
